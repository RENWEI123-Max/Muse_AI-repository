import 'dotenv/config';
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { randomUUID, scryptSync } from 'node:crypto';
import { readdir, readFile, mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import pg from 'pg';
import { buildApp } from '../src/app.js';
import { digest } from '../src/auth.js';

test('B13 report evidence validation, moderator access and retention',async t=>{
 const schema='reports_'+randomUUID().replaceAll('-','');
 const admin=new pg.Pool({connectionString:process.env.DATABASE_URL});
 await admin.query(`CREATE SCHEMA ${schema}`);
 const db=new pg.Pool({connectionString:process.env.DATABASE_URL,options:`-c search_path=${schema}`});
 const directory=await mkdtemp(join(tmpdir(),'maugo-reports-'));
 const previous=process.env.MEDIA_DIRECTORY;process.env.MEDIA_DIRECTORY=directory;
 const app=buildApp(db);
 t.after(async()=>{await app.close();await db.end();await admin.end();await rm(directory,{recursive:true,force:true});if(previous===undefined)delete process.env.MEDIA_DIRECTORY;else process.env.MEDIA_DIRECTORY=previous;});
 const dir=new URL('../server/migrations/',import.meta.url);
 for(const name of (await readdir(dir)).filter(n=>n.endsWith('.sql')).sort()) await db.query(await readFile(new URL(name,dir),'utf8'));
 for(let i=0;i<2;i++) await db.query(await readFile(new URL('013_report_attachments.sql',dir),'utf8'));
 const password='ReportPassword1!';
 const user=async(moderator=false)=>{
  const id=randomUUID(),token=randomUUID(),salt=randomUUID();
  await db.query('INSERT INTO users(id,email,password_hash,token_hash,is_moderator) VALUES($1,$2,$3,$4,$5)',[id,id+'@test.local',salt+':'+scryptSync(password,salt,64).toString('hex'),digest(token),moderator]);
  return {id,token};
 };
 const a=await user(),b=await user(),other=await user(),mod=await user(true);
 const call=(method:any,url:string,u:any,payload?:any)=>app.inject({method,url,headers:u?{authorization:'Bearer '+u.token}:{},payload});
 const png=Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jRZkAAAAASUVORK5CYII=','base64');
 const upload=(u:any,purpose='report',bytes=png,mime='image/png',filename='proof.png')=>app.inject({method:'POST',url:'/media/uploads?'+new URLSearchParams({purpose,filename}),headers:{...(u?{authorization:'Bearer '+u.token}:{}),'content-type':mime},payload:bytes});
 assert.equal((await upload(undefined)).statusCode,401);
 assert.equal((await upload({...a,token:'bad'})).statusCode,401);
 assert.equal((await upload(a,'invalid')).statusCode,400);
 assert.equal((await upload(a,'report',Buffer.alloc(10*1024*1024))).statusCode,413);
 assert.equal((await upload(a,'report',Buffer.from('not an image'))).statusCode,415);
 const wav=Buffer.alloc(48);wav.write('RIFF',0);wav.writeUInt32LE(40,4);wav.write('WAVEfmt ',8);wav.writeUInt32LE(16,16);wav.writeUInt16LE(1,20);wav.writeUInt16LE(1,22);wav.writeUInt32LE(8000,24);wav.writeUInt32LE(16000,28);wav.writeUInt16LE(2,32);wav.writeUInt16LE(16,34);wav.write('data',36);wav.writeUInt32LE(4,40);
 assert.equal((await upload(a,'report',wav,'audio/wav','voice.wav')).statusCode,415);
 const uploaded=await upload(a);assert.equal(uploaded.statusCode,201,uploaded.body);
 const media=uploaded.json();assert.equal(media.purpose,'report');assert.equal(media.kind,'image');
 assert.equal((await call('GET',media.url,mod)).statusCode,403);
 const report=(u:any,attachmentMediaId?:string)=>call('POST','/reports',u,{reportedUserId:b.id,category:'other',reason:'evidence',...(attachmentMediaId?{attachmentMediaId}:{})});
 assert.equal((await report(a,randomUUID())).statusCode,404);
 assert.equal((await report(other,media.id)).statusCode,403);
 const avatar=await upload(a,'avatar');assert.equal(avatar.statusCode,201);
 assert.equal((await report(a,avatar.json().id)).statusCode,400);
 const audio=await upload(a,'post',wav,'audio/wav','voice.wav');assert.equal(audio.statusCode,201);
 assert.equal((await report(a,audio.json().id)).statusCode,400);
 // Independently verify kind checks against legacy/imported report metadata.
 await db.query("UPDATE media_uploads SET purpose='report' WHERE id=$1",[audio.json().id]);
 assert.equal((await report(a,audio.json().id)).statusCode,400);
 assert.equal((await db.query('SELECT * FROM reports')).rowCount,0);
 const created=await report(a,media.id);assert.equal(created.statusCode,201,created.body);
 const evidence={id:media.id,url:media.url};
 assert.deepEqual(created.json().attachment,evidence);
 assert.equal((await db.query('SELECT attachment_media_id FROM reports WHERE id=$1',[created.json().id])).rows[0].attachment_media_id,media.id);
 const detail=await call('GET',`/reports/${created.json().id}`,a);assert.equal(detail.statusCode,200);assert.deepEqual(detail.json().attachment,evidence);
 assert.equal((await call('GET',`/reports/${created.json().id}`,other)).statusCode,404);
 const queue=await call('GET','/admin/reports',mod);assert.equal(queue.statusCode,200);assert.deepEqual(queue.json().items[0].attachment,evidence);
 for(const u of [a,mod]) {const r=await call('GET',media.url,u);assert.equal(r.statusCode,200);assert.deepEqual(r.rawPayload,png);}
 for(const u of [b,other]) assert.equal((await call('GET',media.url,u)).statusCode,403);
 assert.equal((await call('GET',media.url,undefined)).statusCode,401);
 const plain=await report(a);assert.equal(plain.statusCode,201);assert.equal(plain.json().attachment,null);
 assert.equal((await call('GET',`/reports/${plain.json().id}`,a)).json().attachment,null);
 const resolved=await call('POST',`/admin/reports/${created.json().id}/resolve`,mod,{decision:'reject',result:'reviewed'});
 assert.equal(resolved.statusCode,200);assert.deepEqual(resolved.json().attachment,evidence);
 const challenge=await call('DELETE','/users/me',a,{confirm:true});assert.equal(challenge.statusCode,202);
 const deleted=await call('DELETE','/users/me',a,{confirm:true,deletionToken:challenge.json().deletionToken,password});assert.equal(deleted.statusCode,200,deleted.body);
 assert.equal((await db.query('SELECT * FROM media_uploads WHERE uploader_id=$1',[a.id])).rowCount,1);
 assert.equal((await db.query('SELECT * FROM media_deletion_queue WHERE media_id=$1',[media.id])).rowCount,0);
 const retained=await call('GET',media.url,mod);assert.equal(retained.statusCode,200);assert.deepEqual(retained.rawPayload,png);
 await db.query('DELETE FROM reports WHERE id=$1',[created.json().id]);
 assert.equal((await db.query('SELECT * FROM media_uploads WHERE id=$1',[media.id])).rowCount,1);
 assert.deepEqual(await readFile(join(directory,media.id)),png);
 assert.equal((await call('GET',media.url,mod)).statusCode,403);
});
