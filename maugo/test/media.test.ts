import 'dotenv/config';
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { readdir, readFile, mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import pg from 'pg';
import { buildApp } from '../src/app.js';
import { digest } from '../src/auth.js';

test('B8 persistent media, permissions, signatures, limits and sending',async t=>{
 const schema='media_'+randomUUID().replaceAll('-','');
 const admin=new pg.Pool({connectionString:process.env.DATABASE_URL});
 await admin.query(`CREATE SCHEMA ${schema}`);
 const pool=new pg.Pool({connectionString:process.env.DATABASE_URL,options:`-c search_path=${schema}`});
 const directory=await mkdtemp(join(tmpdir(),'maugo-media-'));
 const previous=process.env.MEDIA_DIRECTORY;process.env.MEDIA_DIRECTORY=directory;
 const app=buildApp(pool);
 t.after(async()=>{await app.close();await pool.end();await admin.end();await rm(directory,{recursive:true,force:true});if(previous===undefined) delete process.env.MEDIA_DIRECTORY;else process.env.MEDIA_DIRECTORY=previous;});
 const dir=new URL('../server/migrations/',import.meta.url);
 for(const name of (await readdir(dir)).filter(x=>x.endsWith('.sql')).sort()) await pool.query(await readFile(new URL(name,dir),'utf8'));
 for(let i=0;i<2;i++) await pool.query(await readFile(new URL('009_media.sql',dir),'utf8'));
 const user=async()=>{
  const id=randomUUID(),token=randomUUID();
  await pool.query('INSERT INTO users(id,email,password_hash,token_hash) VALUES($1,$2,$3,$4)',[id,id+'@test.local','unused',digest(token)]);
  return {id,token};
 };
 const a=await user(),b=await user(),other=await user();
 const call=(method:any,url:string,u:any,payload?:any)=>app.inject({method,url,headers:u?{authorization:'Bearer '+u.token}:{},payload});
 const png=Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jRZkAAAAASUVORK5CYII=','base64');
 const opening=await call('POST',`/conversations/${b.id}/opening`,a,{content:'hello'});
 const cid=opening.json().id;
 const upload=(u:any,purpose='chat',bytes=png,mime='image/png',filename='photo.png',conversationId:string|undefined=purpose==='chat'?cid:undefined)=>app.inject({method:'POST',url:'/media/uploads?'+new URLSearchParams({purpose,filename,...(conversationId?{conversationId}:{})}),headers:{...(u?{authorization:'Bearer '+u.token}:{}),'content-type':mime},payload:bytes});
 assert.equal((await upload(undefined)).statusCode,401);
 assert.equal((await upload({...a,token:'bad'})).statusCode,401);
 for(const u of [a,b]) assert.equal((await upload(u)).statusCode,403);
 assert.equal((await call('POST',`/conversations/${cid}/media`,b,{mediaId:randomUUID()})).statusCode,403);
 assert.equal((await upload(other)).statusCode,404);
 assert.equal((await upload(a,'chat',png,'image/png','x.png','')).statusCode,400);
 assert.equal((await call('POST',`/conversations/${cid}/messages`,b,{content:'valid reply'})).statusCode,201);
 for(const filename of ['../photo.png','photo.exe','a/b.png','..\\x.png','x.png.html']) assert.equal((await upload(a,'chat',png,'image/png',filename)).statusCode>=400,true,filename);
 assert.equal((await upload(a,'chat',Buffer.from('<script>evil</script>'),'image/png')).statusCode,415);
 assert.equal((await upload(a,'chat',png,'image/jpeg','photo.jpg')).statusCode,415);
 assert.equal((await upload(a,'chat',png,'application/octet-stream')).statusCode,415);
 assert.equal((await upload(a,'chat',Buffer.alloc(10*1024*1024),'image/png')).statusCode,413);
 assert.equal((await upload(a,'chat',Buffer.alloc(0))).statusCode,400);
 const uploaded=await upload(a); assert.equal(uploaded.statusCode,201,uploaded.body);
 const record=uploaded.json(); assert.equal(record.size,png.length);assert.equal(record.uploaderId,a.id);assert.ok(record.createdAt);
 assert.deepEqual(await readFile(join(directory,record.id)),png);
 const stored=(await pool.query('SELECT * FROM media_uploads WHERE id=$1',[record.id])).rows[0];assert.equal(stored.size_bytes,png.length);assert.equal(stored.mime_type,'image/png');
 assert.equal((await call('GET',record.url,undefined)).statusCode,401);
 assert.equal((await call('GET',record.url,other)).statusCode,404);
 const downloaded=await call('GET',record.url,b);assert.equal(downloaded.statusCode,200);assert.deepEqual(downloaded.rawPayload,png);assert.equal(downloaded.headers['x-content-type-options'],'nosniff');
 assert.equal((await call('POST',`/conversations/${cid}/media`,b,{mediaId:record.id})).statusCode,404);
 assert.equal((await call('POST',`/conversations/${cid}/media`,a,{mediaId:record.id})).statusCode,201);
 assert.equal((await pool.query('SELECT * FROM messages WHERE media_id=$1',[record.id])).rowCount,1);
 const avatar=await upload(a,'avatar');assert.equal(avatar.statusCode,201);
 assert.equal((await call('GET',avatar.json().url,other)).statusCode,403);
 assert.equal((await call('POST',`/conversations/${cid}/media`,a,{mediaId:avatar.json().id})).statusCode,404);
 // Small valid ISO BMFF file: ftyp + free + mdat boxes, padded to the requested byte limit.
 const mp4=(size:number)=>{const data=Buffer.alloc(size);data.writeUInt32BE(24,0);data.write('ftyp',4);data.write('isom',8);data.write('isommp42',16);data.writeUInt32BE(size-24,24);data.write('mdat',28);return data;};
 assert.equal((await upload(a,'post',mp4(30*1024*1024-1),'video/mp4','clip.mp4')).statusCode,201);
 assert.equal((await upload(a,'post',mp4(30*1024*1024),'video/mp4','clip.mp4')).statusCode,413);
 assert.equal((await upload(a,'post',mp4(30*1024*1024+1),'video/mp4','clip.mp4')).statusCode,413);
 assert.equal((await upload(a,'avatar',mp4(64),'video/mp4','clip.mp4')).statusCode,415);
 const wav=Buffer.alloc(48);wav.write('RIFF',0);wav.writeUInt32LE(40,4);wav.write('WAVEfmt ',8);wav.writeUInt32LE(16,16);wav.writeUInt16LE(1,20);wav.writeUInt16LE(1,22);wav.writeUInt32LE(8000,24);wav.writeUInt32LE(16000,28);wav.writeUInt16LE(2,32);wav.writeUInt16LE(16,34);wav.write('data',36);wav.writeUInt32LE(4,40);
 assert.equal((await upload(a,'chat',wav,'audio/wav','voice.wav')).statusCode,201);
 assert.equal((await upload(a,'chat',Buffer.alloc(10*1024*1024),'audio/wav','voice.wav')).statusCode,413);
 assert.equal((await upload(a,'post',png,'image/png','image.png',cid)).statusCode,400);
 await call('PUT',`/blocks/${a.id}`,b);
 assert.equal((await upload(a)).statusCode,403);assert.equal((await upload(b)).statusCode,403);
 assert.equal((await call('GET',record.url,b)).statusCode,403);
 assert.equal((await call('POST',`/conversations/${cid}/media`,a,{mediaId:record.id})).statusCode,403);
 await call('DELETE',`/blocks/${a.id}`,b);
 await pool.query('UPDATE users SET is_suspended=true WHERE id=$1',[a.id]);
 assert.equal((await upload(a,'post')).statusCode,403);assert.equal((await upload(b)).statusCode,403);
 // Rejected requests never create metadata or filesystem leftovers.
 assert.equal((await readdir(directory)).length,4);
 assert.equal((await pool.query('SELECT * FROM media_uploads')).rowCount,4);
});
