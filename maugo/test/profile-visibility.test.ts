import 'dotenv/config';
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { readdir, readFile, mkdtemp, rm } from 'node:fs/promises';
import pg from 'pg';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { buildApp } from '../src/app.js';
import { digest } from '../src/auth.js';

test('B18 migration, global profile visibility and B16 friendship', async t => {
 const schema='visibility_'+randomUUID().replaceAll('-','');
 const admin=new pg.Pool({connectionString:process.env.DATABASE_URL});
 await admin.query(`CREATE SCHEMA ${schema}`);
 const pool=new pg.Pool({connectionString:process.env.DATABASE_URL,options:`-c search_path=${schema}`});
 const directory=await mkdtemp(join(tmpdir(),'maugo-b18-'));
 const previous=process.env.MEDIA_DIRECTORY;process.env.MEDIA_DIRECTORY=directory;
 const app=buildApp(pool);
 t.after(async()=>{await app.close();await pool.end();await admin.query(`DROP SCHEMA ${schema} CASCADE`);await admin.end();await rm(directory,{recursive:true,force:true});if(previous===undefined) delete process.env.MEDIA_DIRECTORY;else process.env.MEDIA_DIRECTORY=previous;});
 const dir=new URL('../server/migrations/',import.meta.url);
 for(const name of (await readdir(dir)).filter(x=>x.endsWith('.sql')&&x<'017').sort()) await pool.query(await readFile(new URL(name,dir),'utf8'));
 const user=async()=>{
  const id=randomUUID(),token=randomUUID();
  await pool.query('INSERT INTO users(id,email,password_hash,token_hash) VALUES($1,$2,$3,$4)',[id,id+'@test.local','unused',digest(token)]);
  return {id,token};
 };
 const a=await user();
 for(let i=0;i<2;i++) await pool.query(await readFile(new URL('017_profile_visibility.sql',dir),'utf8'));
 await pool.query(await readFile(new URL('019_profile_stats.sql',dir),'utf8'));
 await pool.query(await readFile(new URL('021_profile_zodiac.sql',dir),'utf8'));
 assert.equal((await pool.query('SELECT visibility FROM users WHERE id=$1',[a.id])).rows[0].visibility,'everyone');
 const b=await user();
 const call=(method:any,url:string,u:any,payload?:any)=>app.inject({method,url,headers:u?{authorization:'Bearer '+u.token}:{},payload});
 const png=Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jRZkAAAAASUVORK5CYII=','base64');
 const upload=async(purpose:string)=>{
  const r=await app.inject({method:'POST',url:`/media/uploads?purpose=${purpose}&filename=photo.png`,headers:{authorization:'Bearer '+a.token,'content-type':'image/png'},payload:png});
  assert.equal(r.statusCode,201,r.body);return r.json().id;
 };
 const avatar=await upload('avatar'),photo=await upload('post');
 assert.equal((await call('POST','/profiles/me/avatars',a,{action:'add',mediaId:avatar})).statusCode,200);
 assert.equal((await call('POST','/users/me/image-cards',a,{mediaId:photo,type:'portrait'})).statusCode,201);
 const patch=(visibility:any)=>call('PATCH','/profiles/me',a,{visibility});
 assert.equal((await call('GET','/profiles/me',b)).json().visibility,'everyone');
 assert.equal((await call('GET',`/profiles/${a.id}`,b)).statusCode,200);
 assert.equal((await call('PATCH','/profiles/me',undefined,{visibility:'only_me'})).statusCode,401);
 for(const value of ['invalid','',null,7]) assert.equal((await patch(value)).statusCode,400);
 await assert.rejects(pool.query("UPDATE users SET visibility='invalid' WHERE id=$1",[a.id]),{code:'23514'});
 const edited=await patch('only_me');assert.equal(edited.statusCode,200);assert.equal(edited.json().visibility,'only_me');
 assert.equal((await call('GET',`/profiles/${a.id}`,b)).statusCode,403);
 assert.equal((await call('GET',`/profiles/${a.id}`,a)).statusCode,200);
 assert.equal((await call('PATCH','/profiles/me',a,{bio:'kept'})).json().visibility,'only_me');
 await patch('friends');
 assert.equal((await call('GET',`/profiles/${a.id}`,b)).statusCode,403);
 const opening=await call('POST',`/conversations/${b.id}/opening`,a,{content:'Hello'});
 assert.equal(opening.statusCode,201,opening.body);
 const cid=opening.json().id;
 const post=await call('POST','/posts',a,{content:'Friends post',visibility:'friends'});
 assert.equal(post.statusCode,201,post.body);
 const check=async(status:number)=>{
  assert.equal((await call('GET',`/profiles/${a.id}`,b)).statusCode,status);
  assert.equal((await call('GET',`/posts/${post.json().id}`,b)).statusCode,status);
  for(const id of [avatar,photo]) assert.equal((await call('GET',`/media/uploads/${id}`,b)).statusCode,status);
  assert.equal((await call('GET','/profiles/me',a)).statusCode,200);
 };
 await check(403);
 assert.equal((await call('GET','/letters',b)).json().items.length,0);
 assert.equal((await call('GET','/conversations',b)).json().items.length,0);
 const reply=await call('POST',`/conversations/${cid}/messages`,b,{content:'Reply'});
 const collect=await app.inject({method:'POST',url:`/conversations/${cid}/replies/${reply.json().id}/collect`,headers:{authorization:'Bearer '+a.token,'idempotency-key':randomUUID()},payload:{}});
 assert.equal(collect.statusCode,200,collect.body);
 await check(200);
 const batch=(await call('GET','/letters',b)).json();
 assert.equal(batch.items.length,1);
 assert.equal((await call('GET',`/letters/${opening.json().openingMessageId}`,b)).statusCode,200);
 assert.equal((await call('GET','/conversations',b)).json().items.length,1);
 await patch('only_me');
 await check(403);
 assert.equal((await call('GET',`/letters?batchId=${batch.batchId}`,b)).json().items.length,0);
 assert.equal((await call('GET',`/letters/${opening.json().openingMessageId}`,b)).statusCode,404);
 for(const id of [avatar,photo]) assert.equal((await call('GET',`/media/uploads/${id}`,a)).statusCode,200);
 assert.equal((await call('GET','/posts',b)).json().items.length,0);
 assert.equal((await call('GET','/letters',b)).json().items.length,0);
 assert.equal((await call('GET','/conversations',b)).json().items.length,0);
 assert.equal((await call('GET',`/profiles/${a.id}`,a)).statusCode,200);
 await patch('everyone');await check(200);
});
