import 'dotenv/config';
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { readFile,readdir } from 'node:fs/promises';
import pg from 'pg';
import { buildApp } from '../src/app.js';
import { digest } from '../src/auth.js';
test('B11 real database inbox, collection, visibility and permission boundaries',async t=>{
 const admin=new pg.Pool({connectionString:process.env.TEST_DATABASE_URL||process.env.DATABASE_URL});
 const schema='inbox_'+randomUUID().replaceAll('-','');await admin.query(`CREATE SCHEMA ${schema}`);
 const db=new pg.Pool({connectionString:process.env.TEST_DATABASE_URL||process.env.DATABASE_URL,options:`-c search_path=${schema}`});
 const app=buildApp(db);t.after(async()=>{await app.close();await db.end();await admin.end();});
 const dir=new URL('../server/migrations/',import.meta.url);
 for(const f of (await readdir(dir)).filter(f=>f.endsWith('.sql')).sort())await db.query(await readFile(new URL(f,dir),'utf8'));
 async function user(){const id=randomUUID(),token=randomUUID();await db.query('INSERT INTO users(id,email,password_hash,token_hash) VALUES($1,$2,$3,$4)',[id,id+'@test.local','unused',digest(token)]);return {id,token};}
 const a=await user(),b=await user(),x=await user();
 const call=(method:any,url:string,u=a,payload?:any)=>app.inject({method,url,headers:{authorization:'Bearer '+u.token},payload});
 const v=(await call('POST',`/conversations/${b.id}/opening`,a,{content:'Opening'})).json();const base='/conversations/'+v.id;
 assert.equal((await app.inject('/conversations')).statusCode,401);
 for(const suffix of ['/messages','/replies/pending'])assert.equal((await call('GET',base+suffix,x)).statusCode,404);
 assert.equal((await call('PATCH',base,x,{hidden:true})).statusCode,404);
 assert.equal((await call('GET','/conversations?limit=0')).statusCode,400);
 assert.equal((await call('GET','/conversations')).json().items.length,1);
 assert.equal((await call('GET','/conversations?tab=friends')).json().items.length,0);
 assert.equal((await call('PATCH',base,a,{remark:'Tea',pinned:true,muted:true,following:true,background:'sand',bubble:'blue'})).json().remark,'Tea');
 assert.equal((await call('GET','/conversations?tab=friends')).json().items.length,1);
 assert.equal((await call('GET','/conversations?tab=friends',b)).json().items.length,0);
 assert.equal((await call('POST',base+'/messages',a,{content:'Wait'})).statusCode,403);
 for(const u of [a,b])assert.equal((await call('POST',base+'/media',u,{mediaId:randomUUID()})).statusCode,403);
 assert.equal((await call('GET',base+'/messages?search=absent')).json().items.length,0);
 assert.equal((await call('POST',base+'/messages',b,{content:'image',kind:'image',mediaId:randomUUID()})).statusCode,400);
 assert.equal((await call('PATCH',base,a,{clearHistory:true})).statusCode,200);
 assert.equal((await call('GET',base+'/messages')).json().items.length,0);
 assert.equal((await call('POST',`/conversations/${b.id}/opening`,a,{content:'Again'})).statusCode,409);
 assert.equal((await call('POST',base+'/messages',a,{content:'Still waiting'})).statusCode,403);
 // Even a legacy/malformed opener-authored reply cannot unlock the permission ledger.
 const fake=randomUUID();await db.query("INSERT INTO messages(id,conversation_id,sender_id,kind,content) VALUES($1,$2,$3,'reply','Legacy opener reply')",[fake,v.id,a.id]);
 await app.inject({method:'POST',url:base+'/replies/'+fake+'/collect',headers:{authorization:'Bearer '+b.token,'idempotency-key':'legacy'},payload:{}});
 assert.equal((await db.query('SELECT unlocked_at FROM conversations WHERE id=$1',[v.id])).rows[0].unlocked_at,null);
 assert.equal((await call('POST',base+'/messages',a,{content:'Still locked'})).statusCode,403);
 await call('PATCH',base,a,{clearHistory:true});
 const m=(await call('POST',base+'/messages',b,{content:'Secret reply'})).json();
 assert.equal((await call('GET',base+'/messages')).json().items.length,0);
 assert.ok(!(await call('GET','/conversations')).body.includes('Secret reply'));
 const pending=(await call('GET',base+'/replies/pending')).json();assert.equal(pending.items[0].id,m.id);assert.equal(pending.freeRemaining,10);assert.ok(!JSON.stringify(pending).includes('Secret'));
 const collect=await app.inject({method:'POST',url:base+'/replies/'+m.id+'/collect',headers:{authorization:'Bearer '+a.token,'idempotency-key':'b11'},payload:{}});assert.equal(collect.statusCode,200,collect.body);
 assert.equal((await call('GET',base+'/replies/pending')).json().freeRemaining,9);
 assert.equal((await call('GET',base+'/replies/pending')).json().items.length,0);
 assert.equal((await call('GET','/conversations')).json().items[0].unreadCount,1);
 assert.equal((await call('GET',base+'/messages?search=Secret&markRead=true')).json().items[0].id,m.id);
 assert.equal((await call('GET','/conversations')).json().items[0].unreadCount,0);
 await call('PATCH',base,a,{clearHistory:true});assert.equal((await call('GET',base+'/messages')).json().items.length,0);
 assert.ok((await call('GET',base+'/messages',b)).json().items.length>0);
 assert.equal((await call('POST',base+'/messages',a,{content:'Unlocked remains'})).statusCode,201);
 await call('PATCH',base,a,{hidden:true});assert.equal((await call('GET','/conversations')).json().items.length,0);
 assert.equal((await call('GET','/conversations?hidden=true')).json().items.length,1);
 await call('PATCH',base,a,{hidden:false});assert.equal((await call('GET','/conversations')).json().items.length,1);
 await db.query('INSERT INTO user_blocks(blocker_id,blocked_id) VALUES($1,$2)',[b.id,a.id]);
 for(const u of [a,b])assert.equal((await call('POST',base+'/messages',u,{content:'Blocked'})).statusCode,403);
 // Two independent lists use separate offsets and deterministic pagination.
 const peer=await user();await call('POST',`/conversations/${peer.id}/opening`,a,{content:'Second'});
 const first=(await call('GET','/conversations?limit=1')).json(),second=(await call('GET','/conversations?limit=1&offset=1')).json();
 assert.equal(first.hasMore,true);assert.equal(second.hasMore,false);assert.notEqual(first.items[0].id,second.items[0].id);
 assert.equal((await call('GET','/conversations?tab=friends&offset=1')).json().items.length,0);
});
