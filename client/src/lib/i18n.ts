export function tr(value: unknown): string {
  const text=String(value??'')
  if(locale.value==='en')return text
  return businessKo[text] ?? text
    .replace(/^Pay (\d+) diamonds$/, '다이아몬드 $1개 결제')
    .replace(/^Filter Pass · (\d+) days remaining$/, '필터 패스 · $1일 남음')
    .replace(/^Filter Pass unlocked for (\d+) days\.$/, '$1일 필터 패스가 활성화됐어요.')
    .replace(/^(\d+) day(s?)$/, '$1일')
    .replace(/^Open letter (\d+)$/, '$1번 편지 열기')
    .replace(/^Avatar (\d+)$/, '아바타 $1')
    .replace(/^Restore (\d+)$/, '$1번 복원')
    .replace(/^Choose (.+)$/, (_, name:string) => '선택: '+(businessKo[name]??name))
    .replace(/^Filter (.+)$/, (_, gender:string) => '필터: '+(businessKo[gender]??gender))
    .replace(/^(\d+) free today$/, '오늘 무료 $1개')
    .replace(/^(\d+) diamonds per reply$/, '답장당 다이아몬드 $1개')
    .replace(/^Collecting one reply costs (\d+) diamonds\.$/, '답장 한 개 받는 비용은 다이아몬드 $1개예요.')
    .replace(/^Collect reply · (\d+) diamonds$/, '답장 받기 · 다이아몬드 $1개')
    .replace(/^ \((\d+)s\)$/, ' ($1초)')
    .replace(/^Photo upload failed\. (.+) You can still submit without a photo\.$/, (_, message:string) => '사진 업로드에 실패했어요. '+tr(message)+' 사진 없이 제출할 수 있어요.')
    .replace(/^Microphone unavailable\. Connect a microphone and try again\. \((.+)\)$/, '마이크를 사용할 수 없어요. 마이크를 연결하고 다시 시도하세요. ($1)')
    .replace(/^Voice upload\/send failed\. (.+) Your recording is available to retry\.$/, (_, message:string) => '음성 업로드 또는 전송에 실패했어요. '+tr(message)+' 녹음은 유지되며 다시 시도할 수 있어요.')
    .replace(/^s$/, '')
}
