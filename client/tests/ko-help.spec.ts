import {test,expect} from '@playwright/test'

test('Korean help and FAQ translate and switch back to English',async({page,request})=>{
 const seed=await request.post((process.env.D6_API_ROOT||'http://127.0.0.1:3001')+'/__c5/seed',{data:{mode:'read'}})
 expect(seed.ok()).toBeTruthy()
 const user=await seed.json()
 await page.goto('/?auth=consent')
 await page.locator('#accept-terms').check();await page.locator('#terms-continue').click()
 await page.locator('#auth-email').fill(user.email);await page.locator('#auth-password').fill(user.password)
 await page.locator('#auth-form button.primary').click();await page.getByRole('button',{name:'Meet your letters'}).click()
 await page.locator('#open-profile').click();await page.locator('#open-settings').click()
 await page.locator('#language-settings').click();await page.locator('[data-language="ko"]').click()
 await page.locator('#settings-back').click();await page.locator('#help-settings').click()
 const body=page.locator('.settings-body')
 await expect(body).toContainText('답장 10개')
 await expect(page.locator('#help-centre')).toHaveText('도움말 센터')
 await expect(page.locator('#help-delete')).toHaveText('계정 삭제')
 await expect(page.locator('#support-feedback')).toHaveText('피드백')
 await expect(body).not.toContainText('Feedback is saved only on this device.')
 await expect(body).toHaveCSS('opacity','1')
 await page.screenshot({path:'docs/ko-help-fixed.png',fullPage:true})
 await page.locator('#help-centre').click()
 await expect(body.locator('details')).toHaveCount(6)
 for(const detail of await body.locator('details').all()){
  await expect(detail.locator('summary')).toHaveText(/[가-힣]/)
  await detail.locator('summary').click()
  await expect(detail.locator('p')).toHaveText(/[가-힣]/)
 }
 await expect(body).toContainText('매일 답장 10개를 무료로 받을 수 있어요.')
 await expect(body).toHaveCSS('opacity','1')
 await page.screenshot({path:'docs/ko-help-faq-fixed.png',fullPage:true})
 await page.locator('#settings-back').click();await page.locator('#settings-back').click()
 await page.locator('#language-settings').click();await page.locator('[data-language="en"]').click()
 await page.locator('#settings-back').click();await page.locator('#help-settings').click()
 await expect(body).toContainText('Each day, 10 replies are free')
 await expect(page.locator('#help-centre')).toHaveText('Help centre')
 await page.locator('#help-centre').click()
 await body.locator('summary').nth(1).click()
 await expect(body.locator('details').nth(1).locator('p')).toHaveText('Collect 10 replies free each day. Further replies cost 10 diamonds each and need your confirmation.')
})
