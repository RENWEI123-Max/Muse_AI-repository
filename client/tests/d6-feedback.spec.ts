import {test,expect} from '@playwright/test'
test('B19 feedback is sent, visible to moderation, and rate limit preserves input',async({page,request})=>{
 test.setTimeout(120000)
 const root='http://127.0.0.1:3179'
 const seed=await request.post(root+'/__c5/seed',{data:{mode:'empty'}});expect(seed.ok()).toBeTruthy()
 const user=await seed.json(),headers={Authorization:`Bearer ${user.token}`}
 expect((await request.post(root+'/__d6/setup',{data:{id:user.id}})).ok()).toBeTruthy()
 await page.goto('/?auth=consent');await page.locator('#accept-terms').check();await page.locator('#terms-continue').click()
 await page.locator('#auth-email').fill(user.email);await page.locator('#auth-password').fill(user.password)
 await page.locator('#auth-form button.primary').click();await page.getByRole('button',{name:'Meet your letters'}).click()
 await page.locator('#open-profile').click();await page.locator('#open-settings').click();await page.locator('#feedback-settings').click()
 await expect(page.locator('#save-feedback')).toBeDisabled()
 await page.locator('#feedback-text').fill('D6 round three: real B19 browser submission')
 await page.locator('#feedback-email').fill('reader@example.com')
 const sent=page.waitForResponse(r=>r.url().endsWith('/feedback')&&r.request().method()==='POST')
 await page.locator('#save-feedback').click();const response=await sent;expect(response.status()).toBe(201)
 expect(response.request().postDataJSON()).toEqual({content:'D6 round three: real B19 browser submission',type:'Suggestion',contact:'reader@example.com'})
 const receipt=await response.json();expect(receipt.status).toBe('new')
 await expect(page.locator('[role=status]')).toContainText(receipt.id);await expect(page.locator('#feedback-text')).toBeEmpty()
 await page.screenshot({path:'docs/d6-round3/feedback-success.png'})
 const queue=await request.get(root+'/admin/feedback?status=new',{headers});expect(queue.ok()).toBeTruthy()
 expect((await queue.json()).items).toEqual(expect.arrayContaining([expect.objectContaining({id:receipt.id,content:'D6 round three: real B19 browser submission',contact:'reader@example.com',status:'new'})]))
 expect(await page.evaluate(()=>Object.keys(localStorage).filter(k=>k.startsWith('maugo-feedback-')))).toEqual([])
 for(let i=0;i<4;i++)expect((await request.post(root+'/feedback',{headers,data:{content:'Rate limit verification '+i}})).status()).toBe(201)
 await page.locator('#settings-back').click();await page.locator('#help-settings').click();await page.locator('#support-feedback').click()
 await page.locator('#feedback-text').fill('Keep this input after the server refuses submission')
 const failed=page.waitForResponse(r=>r.url().endsWith('/feedback')&&r.request().method()==='POST')
 await page.locator('#save-feedback').click();expect((await failed).status()).toBe(429)
 await expect(page.getByRole('alert')).toHaveText('Feedback limit reached. Try again in an hour.')
 await expect(page.locator('#feedback-text')).toHaveValue('Keep this input after the server refuses submission')
 await expect(page.locator('#save-feedback')).toBeEnabled();await expect(page.locator('[role=status]')).toHaveCount(0)
 await page.screenshot({path:'docs/d6-round3/feedback-failure.png'})
})
